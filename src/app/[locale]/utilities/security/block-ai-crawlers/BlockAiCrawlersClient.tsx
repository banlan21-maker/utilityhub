'use client';

import React, { useCallback, useMemo, useState } from 'react';
import { useLocale, useTranslations } from 'next-intl';
import { ShieldOff, Copy, Check, Download, ChevronDown, ChevronRight } from 'lucide-react';
import NavigationActions from '@/app/components/NavigationActions';
import ToolHeader from '@/app/components/ToolHeader';
import RelatedTools from '@/app/components/RelatedTools';
import ShareBar from '@/app/components/ShareBar';
import { AI_BOTS, normalizePaths, hasWildcard, type AiBot } from '@/lib/ai-bots';
import s from './block-ai-crawlers.module.css';
import { ui } from '@/app/components/ui';

type Scope = 'all' | 'folder' | 'image';
type Output = 'robots' | 'meta' | 'header' | 'llms';
type HeaderPlatform = 'apache' | 'nginx';

const MAJOR_IDS = AI_BOTS.filter((b) => b.major).map((b) => b.id);

export default function BlockAiCrawlersClient({ seo }: { seo?: React.ReactNode }) {
  const t = useTranslations('BlockAiCrawlers');
  const locale = useLocale();
  const isKo = locale === 'ko';

  const [selected, setSelected] = useState<Set<string>>(() => new Set(MAJOR_IDS));
  const [moreOpen, setMoreOpen] = useState(false);
  const [scope, setScope] = useState<Scope>('all');
  const [folderInput, setFolderInput] = useState('');
  const [output, setOutput] = useState<Output>('robots');
  const [headerPlatform, setHeaderPlatform] = useState<HeaderPlatform>('apache');
  const [copied, setCopied] = useState(false);
  const [toast, setToast] = useState<string | null>(null);

  const showToast = useCallback((msg: string) => {
    setToast(msg);
    setTimeout(() => setToast(null), 2600);
  }, []);

  const toggleBot = (id: string) => {
    setSelected((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  };

  const selectMajor = () => setSelected(new Set(MAJOR_IDS));
  const deselectAll = () => setSelected(new Set());

  const selectedBots = useMemo(
    () => AI_BOTS.filter((b) => selected.has(b.id)),
    [selected],
  );
  const moreSelectedCount = useMemo(
    () => AI_BOTS.filter((b) => !b.major && selected.has(b.id)).length,
    [selected],
  );

  const folderPaths = useMemo(() => normalizePaths(folderInput), [folderInput]);
  const wildcardWarn = scope === 'folder' && hasWildcard(folderInput);

  // 폴더 입력 정규화 (onBlur)
  const handleFolderBlur = () => {
    if (scope !== 'folder') return;
    const trimmed = folderInput.trim();
    if (!trimmed) {
      setScope('all');
      showToast(t('path_empty_changed'));
      return;
    }
    const paths = normalizePaths(folderInput);
    if (paths.length === 0) {
      setScope('all');
      showToast(t('path_empty_changed'));
      return;
    }
    const normalized = paths.join(', ');
    if (normalized !== trimmed) {
      setFolderInput(normalized);
      showToast(t('path_normalized', { path: normalized }));
    }
  };

  // ── 코드 생성 ────────────────────────────────────────────────
  const generatedCode = useMemo(() => {
    if (selectedBots.length === 0) return '';

    // 산출물 생성 직전 한 번 더 정규화 (이중 안전)
    const paths = scope === 'folder' ? normalizePaths(folderInput) : [];
    const effectiveScope: Scope = scope === 'folder' && paths.length === 0 ? 'all' : scope;

    const disallowLines = (): string[] => {
      if (effectiveScope === 'all') return ['Disallow: /'];
      if (effectiveScope === 'image') {
        return ['Disallow: /*.jpg$', 'Disallow: /*.jpeg$', 'Disallow: /*.png$', 'Disallow: /*.gif$', 'Disallow: /*.webp$', 'Disallow: /*.svg$'];
      }
      return paths.map((p) => `Disallow: ${p}`);
    };

    if (output === 'robots') {
      const blocks = selectedBots.map((b) => {
        const lines = [`User-agent: ${b.userAgent}`, ...disallowLines()];
        return lines.join('\n');
      });
      return `# AI crawler blocking — generated by theutilhub.com\n# Normal search engines (Googlebot, Bingbot) are NOT affected.\n\n${blocks.join('\n\n')}`;
    }

    if (output === 'meta') {
      // 메타태그는 페이지 단위 — noai/noimageai
      const content = effectiveScope === 'image' ? 'noimageai' : 'noai, noimageai';
      return `<!-- Add inside <head> of each HTML page -->\n<meta name="robots" content="${content}">`;
    }

    if (output === 'header') {
      const headerVal = effectiveScope === 'image' ? 'noimageai' : 'noai, noimageai';
      if (headerPlatform === 'apache') {
        if (effectiveScope === 'folder' && paths.length > 0) {
          return paths
            .map((p) => `<Directory "/var/www/html${p}">\n  Header set X-Robots-Tag "${headerVal}"\n</Directory>`)
            .join('\n');
        }
        return `# Apache — add to .htaccess or httpd.conf\nHeader set X-Robots-Tag "${headerVal}"`;
      }
      // nginx
      if (effectiveScope === 'folder' && paths.length > 0) {
        return paths
          .map((p) => `location ${p} {\n  add_header X-Robots-Tag "${headerVal}";\n}`)
          .join('\n');
      }
      return `# Nginx — add to server block, then reload\nadd_header X-Robots-Tag "${headerVal}";`;
    }

    // llms.txt
    return `# llms.txt — AI usage policy for theutilhub.com\n# Generated by theutilhub.com\n\nUser-agent: *\nDisallow: /\n\n# Explicitly blocked AI crawlers:\n${selectedBots.map((b) => `# - ${b.userAgent} (${b.company})`).join('\n')}`;
  }, [selectedBots, scope, folderInput, output, headerPlatform]);

  const handleCopy = async () => {
    if (!generatedCode) return;
    try {
      await navigator.clipboard.writeText(generatedCode);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      showToast(t('copy_fallback'));
    }
  };

  const handleDownload = () => {
    if (!generatedCode) return;
    const filename =
      output === 'robots' ? 'robots.txt' :
      output === 'llms' ? 'llms.txt' :
      output === 'meta' ? 'ai-block-meta.html' :
      headerPlatform === 'apache' ? '.htaccess' : 'nginx-ai-block.conf';
    const blob = new Blob([generatedCode], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  const noBots = selectedBots.length === 0;

  // 출력별 가이드/경고
  const guide = useMemo(() => {
    if (output === 'robots') return t('guide_robots');
    if (output === 'meta') return t('guide_meta');
    if (output === 'llms') return t('guide_llms');
    return headerPlatform === 'apache' ? t('guide_header_apache') : t('guide_header_nginx');
  }, [output, headerPlatform, t]);

  // 폴더 차단 + meta/llms 부적합 경고
  const scopeMismatchWarning = useMemo(() => {
    if (scope !== 'folder') return null;
    if (output === 'meta') return t('meta_folder_warning');
    if (output === 'llms') return t('llms_folder_warning');
    return null;
  }, [scope, output, t]);

  const trustBadge = isKo ? '표준 robots.txt 규격' : 'Standard robots.txt spec';

  const renderBotCard = (bot: AiBot) => (
    <label
      key={bot.id}
      className={`${s.bot_card} ${selected.has(bot.id) ? s.bot_card_active : ''}`}
    >
      <input
        type="checkbox"
        className={s.bot_checkbox}
        checked={selected.has(bot.id)}
        onChange={() => toggleBot(bot.id)}
        aria-label={bot.userAgent}
      />
      <span className={s.bot_info}>
        <span className={s.bot_name}>{bot.userAgent}</span>
        <span className={s.bot_company}>{bot.company} · {isKo ? bot.purposeKo : bot.purposeEn}</span>
      </span>
    </label>
  );

  return (
    <div className={s.container}>
      <NavigationActions />

      <ToolHeader icon={<ShieldOff />} title={t('title')} subtitle={t('subtitle')} />

      {/* STEP 1: 봇 선택 */}
      <section className={ui.card}>
        <div className={ui.cardTitle}>{t('step_bots')}</div>
        <div className={s.bot_actions}>
          <button className={`${ui.button} ${ui.secondary} ${ui.sm}`} onClick={selectMajor}>{t('select_all_major')}</button>
          <button className={`${ui.button} ${ui.secondary} ${ui.sm}`} onClick={deselectAll}>{t('deselect_all')}</button>
        </div>

        <div className={s.bot_group_label}>{t('bots_major')}</div>
        <div className={s.bot_grid}>
          {AI_BOTS.filter((b) => b.major).map(renderBotCard)}
        </div>

        <div className={s.accordion_header} onClick={() => setMoreOpen((v) => !v)} role="button" aria-expanded={moreOpen}>
          <span className={`${s.bot_group_label} ${s.no_margin}`}>
            {moreOpen ? <ChevronDown size={14} className={s.chev} /> : <ChevronRight size={14} className={s.chev} />}
            {' '}{t('bots_more')}
          </span>
          <span className={s.accordion_count}>{t('bots_more_count', { n: moreSelectedCount })}</span>
        </div>
        {moreOpen && (
          <div className={`${s.bot_grid} ${s.more_grid}`}>
            {AI_BOTS.filter((b) => !b.major).map(renderBotCard)}
          </div>
        )}
      </section>

      {/* STEP 2: 차단 범위 */}
      <section className={ui.card}>
        <div className={ui.cardTitle}>{t('step_scope')}</div>
        <div className={s.scope_list}>
          {([
            ['all', t('scope_all'), t('scope_all_desc')],
            ['folder', t('scope_folder'), t('scope_folder_desc')],
            ['image', t('scope_image'), t('scope_image_desc')],
          ] as [Scope, string, string][]).map(([val, label, desc]) => (
            <label key={val} className={`${s.scope_card} ${scope === val ? s.scope_card_active : ''}`}>
              <input
                type="radio"
                className={s.scope_radio}
                checked={scope === val}
                onChange={() => setScope(val)}
                aria-label={label}
              />
              <span>
                <span className={s.scope_label}>{label}</span>
                <span className={s.scope_desc}>{desc}</span>
              </span>
            </label>
          ))}
        </div>

        {scope === 'folder' && (
          <div className={s.folder_input_wrap}>
            <input
              type="text"
              className={`${ui.input} ${s.folder_input}`}
              value={folderInput}
              onChange={(e) => setFolderInput(e.target.value)}
              onBlur={handleFolderBlur}
              placeholder={t('folder_placeholder')}
              aria-label={t('scope_folder')}
            />
            {wildcardWarn && <div className={`${ui.notice} ${ui.amber} ${s.box_gap}`} aria-live="polite">{t('path_wildcard_warning')}</div>}
          </div>
        )}
      </section>

      {/* STEP 3: 산출물 */}
      <section className={`${ui.card} ${s.output_section}`}>
        <div className={ui.cardTitle}>{t('step_output')}</div>
        <div className={`${ui.segmented} ${s.output_tabs}`}>
          {([
            ['robots', t('output_robots')],
            ['meta', t('output_meta')],
            ['header', t('output_header')],
            ['llms', t('output_llms')],
          ] as [Output, string][]).map(([val, label]) => (
            <button
              key={val}
              className={`${ui.segment} ${output === val ? ui.segmentActive : ''}`}
              onClick={() => setOutput(val)}
              aria-label={label}
            >
              {label}
            </button>
          ))}
        </div>

        {output === 'header' && (
          <div className={`${ui.chips} ${s.platform_sub_tabs}`}>
            {(['apache', 'nginx'] as HeaderPlatform[]).map((p) => (
              <button
                key={p}
                className={`${ui.chip} ${ui.pill} ${headerPlatform === p ? ui.chipActive : ''}`}
                onClick={() => setHeaderPlatform(p)}
                aria-label={p}
              >
                {p === 'apache' ? 'Apache' : 'Nginx'}
              </button>
            ))}
          </div>
        )}

        {/* 코드 박스 */}
        <div className={s.code_wrap}>
          <div className={s.code_toolbar}>
            <span className={s.trust_badge}>{trustBadge}</span>
            <div className={s.toolbar_actions}>
              <button
                className={`${s.tool_btn} ${copied ? s.tool_btn_done : ''}`}
                onClick={handleCopy}
                disabled={noBots}
                aria-disabled={noBots}
                aria-label={t('copy_btn')}
              >
                {copied ? <Check size={14} /> : <Copy size={14} />}
                {copied ? t('copy_done') : t('copy_btn')}
              </button>
              <button
                className={s.tool_btn}
                onClick={handleDownload}
                disabled={noBots}
                aria-disabled={noBots}
                aria-label={t('download_btn')}
              >
                <Download size={14} />
                {t('download_btn')}
              </button>
            </div>
          </div>
          <pre className={s.code_body} role="textbox" aria-readonly="true" aria-live="polite">
            {generatedCode || ' '}
          </pre>
        </div>

        {/* 봇 0개 오버레이 */}
        {noBots && (
          <div className={s.no_bots_overlay} role="status" aria-live="polite">
            <div className={s.no_bots_msg}>{t('no_bots_title')}</div>
            <button className={`${ui.button} ${ui.primary} ${ui.sm}`} onClick={selectMajor}>{t('no_bots_recover')}</button>
          </div>
        )}

        {scopeMismatchWarning && <div className={`${ui.notice} ${ui.amber} ${s.box_gap}`}>{scopeMismatchWarning}</div>}
        {!noBots && <div className={`${ui.notice} ${ui.gray} ${s.box_gap}`}>{guide}</div>}
      </section>

      {/* AI 봇별 차단 효과 표 */}
      <section className={ui.card}>
        <div className={ui.cardTitle}>{t('effect_title')}</div>
        <div className={s.effect_table_wrap}>
          <table className={s.effect_table}>
            <thead>
              <tr>
                <th>{t('effect_bot')}</th>
                <th>{t('effect_company')}</th>
                <th>{t('effect_purpose')}</th>
              </tr>
            </thead>
            <tbody>
              {selectedBots.map((b) => (
                <tr key={b.id}>
                  <td className={s.effect_bot_name}>{b.userAgent}</td>
                  <td>{b.company}</td>
                  <td>{isKo ? b.purposeKo : b.purposeEn}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      {/* 검증 안내 */}
      <section className={ui.card}>
        <div className={ui.cardTitle}>{t('verify_title')}</div>
        <div className={`${ui.notice} ${ui.green}`}>{t('verify_desc')}</div>
      </section>

      {toast && <div className={s.toast}>{toast}</div>}

      <ShareBar title={t('title')} description={t('subtitle')} />
      <RelatedTools toolId="utilities/security/block-ai-crawlers" />

      {seo}
    </div>
  );
}
